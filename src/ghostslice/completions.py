"""Shell completions (v1.0), generated from the live parser.

`ghostslice completions bash|zsh` prints a completion script
whose command and flag lists are walked out of the argparse
parser the CLI itself uses — one source of truth, so the scripts
cannot drift from the commands (the test suite pins the shipped
copies in examples/completions/ byte-equal to fresh output, and
pins that every subcommand and flag appears).

The generated scripts are deliberately simple: they complete
subcommand names at the top level, each subcommand's flags after
it, and nested subcommands (cache stats/clear) one level down.
Filenames fall back to the shell default everywhere else.
"""
from __future__ import annotations

import argparse

SHELLS = ("bash", "zsh")


def _flags_of(parser: argparse.ArgumentParser) -> list[str]:
    flags: list[str] = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            continue
        for opt in action.option_strings:
            if opt not in flags:
                flags.append(opt)
    return flags


def _subcommands(parser: argparse.ArgumentParser) -> dict:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action.choices
    return {}


def completion_data(parser: argparse.ArgumentParser) -> dict:
    """{command: {"flags": [...], "subcommands": {name: {"flags":
    [...]}}}} walked from the parser, names sorted."""
    data: dict = {}
    for name, sub_parser in sorted(_subcommands(parser).items()):
        entry = {"flags": _flags_of(sub_parser), "subcommands": {}}
        for sub_name, nested in sorted(_subcommands(sub_parser).items()):
            entry["subcommands"][sub_name] = {
                "flags": _flags_of(nested), "subcommands": {}}
        data[name] = entry
    return data


def _header(shell: str) -> list[str]:
    return [
        f"# GhostSlice shell completions for {shell}.",
        "# Generated by `ghostslice completions " + shell + "` from the",
        "# live argument parser; do not edit by hand — regenerate.",
        "# Token counts everywhere in GhostSlice output are estimates.",
    ]


def build_bash(parser: argparse.ArgumentParser) -> str:
    data = completion_data(parser)
    root_flags = " ".join(_flags_of(parser))
    lines = _header("bash") + [
        "",
        "_ghostslice() {",
        "    local cur prev cmd sub",
        '    COMPREPLY=()',
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    prev="${COMP_WORDS[COMP_CWORD-1]}"',
        '    cmd="${COMP_WORDS[1]:-}"',
        '    sub="${COMP_WORDS[2]:-}"',
        "    if [[ ${COMP_CWORD} -eq 1 ]]; then",
        '        COMPREPLY=( $(compgen -W "'
        + " ".join(data) + '" -- "$cur") )',
        "        return 0",
        "    fi",
        '    case "$cmd" in',
    ]
    for name, entry in sorted(data.items()):
        words = list(entry["subcommands"]) + entry["flags"]
        if not words:
            continue
        lines.append(f"        {name})")
        if entry["subcommands"]:
            lines += [
                "            if [[ ${COMP_CWORD} -eq 2 ]]; then",
                '                COMPREPLY=( $(compgen -W "'
                + " ".join(words) + '" -- "$cur") )',
                "                return 0",
                "            fi",
                '            case "$sub" in',
            ]
            for sub_name, sub_entry in sorted(entry["subcommands"].items()):
                if sub_entry["flags"]:
                    lines += [
                        f"                {sub_name})",
                        '                    COMPREPLY=( $(compgen -W "'
                        + " ".join(sub_entry["flags"]) + '" -- "$cur") )',
                        "                    return 0",
                        "                    ;;",
                    ]
            lines += [
                "            esac",
                "            ;;",
            ]
        else:
            lines += [
                '            COMPREPLY=( $(compgen -W "'
                + " ".join(words) + '" -- "$cur") )',
                "            return 0",
                "            ;;",
            ]
    lines += [
        "    esac",
        "    return 0",
        "}",
        "",
        "complete -o default -F _ghostslice ghostslice",
        f"# Top-level flags (before the subcommand): {root_flags}",
        "",
    ]
    return "\n".join(lines)


def build_zsh(parser: argparse.ArgumentParser) -> str:
    data = completion_data(parser)
    root_flags = " ".join(_flags_of(parser))
    lines = _header("zsh") + [
        "#compdef ghostslice",
        "",
        "_ghostslice() {",
        "    local -a commands",
        "    commands=(",
    ]
    for name in data:
        lines.append(f"        '{name}'")
    lines += [
        "    )",
        "    if (( CURRENT == 2 )); then",
        "        _describe -t commands 'ghostslice command' commands",
        "        return",
        "    fi",
        '    case "$words[2]" in',
    ]
    for name, entry in sorted(data.items()):
        words = list(entry["subcommands"]) + entry["flags"]
        if not words:
            continue
        lines.append(f"        {name})")
        if entry["subcommands"]:
            lines += [
                "            if (( CURRENT == 3 )); then",
                "                local -a subs",
                "                subs=(",
            ]
            for sub_name in entry["subcommands"]:
                lines.append(f"                    '{sub_name}'")
            lines += [
                "                )",
                "                _describe -t subcommands 'subcommand' subs",
                "                return",
                "            fi",
                '            case "$words[3]" in',
            ]
            for sub_name, sub_entry in sorted(entry["subcommands"].items()):
                if sub_entry["flags"]:
                    lines += [
                        f"                {sub_name})",
                        "                    _arguments " + " ".join(
                            f"'{f}'" for f in sub_entry["flags"]),
                        "                    ;;",
                    ]
            lines += [
                "            esac",
                "            ;;",
            ]
        else:
            lines += [
                "            _arguments " + " ".join(
                    f"'{w}'" for w in words),
                "            ;;",
            ]
    lines += [
        "    esac",
        "}",
        "",
        "_ghostslice \"$@\"",
        f"# Top-level flags (before the subcommand): {root_flags}",
        "",
    ]
    return "\n".join(lines)


def build_completions(parser: argparse.ArgumentParser, shell: str) -> str:
    if shell == "bash":
        return build_bash(parser)
    if shell == "zsh":
        return build_zsh(parser)
    raise ValueError(f"unknown shell: {shell} (choose from {', '.join(SHELLS)})")
