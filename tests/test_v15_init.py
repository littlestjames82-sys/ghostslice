class TestAuditFixes:
    def test_guard_in_comment_or_string_does_not_nominate(self, tmp_path):
        root = tmp_path / "guardcomment"
        root.mkdir()
        write(root, "src/util.py",
              '# if __name__ == "__main__":\n'
              'DOC = "if __name__ == \'__main__\':"\n\n\n'
              "def util():\n    return 1\n")
        paths = [c["path"] for c in find_entry_candidates(scan(root))]
        assert "src/util.py" not in paths

    def test_nested_guard_does_not_nominate(self, tmp_path):
        root = tmp_path / "guardnested"
        root.mkdir()
        write(root, "src/util.py",
              "def boot():\n"
              '    if __name__ == "__main__":\n'
              "        return 1\n"
              "    return 0\n")
        paths = [c["path"] for c in find_entry_candidates(scan(root))]
        assert "src/util.py" not in paths

    def test_unparseable_file_falls_back_to_textual_guard(self, tmp_path):
        root = tmp_path / "guardbroken"
        root.mkdir()
        write(root, "src/broken.py",
              'if __name__ == "__main__":\n    main(\n')
        cands = {c["path"]: c for c in find_entry_candidates(scan(root))}
        assert "src/broken.py" in cands
        assert any("__main__" in s for s in cands["src/broken.py"]["signals"])

    def test_config_dir_under_generated_dir_not_structured(self, tmp_path):
        root = tmp_path / "genconfig"
        root.mkdir()
        write(root, "gen/code.py",
              "# @generated by fixture\n\n\ndef fetch():\n    return None\n")
        body = "# @generated by fixture\n" + "".join(
            f"key_{i}: value-{i}\n" for i in range(45))
        write(root, "gen/sub/a.yaml", body)
        write(root, "gen/sub/b.yaml", body.replace("key_", "opt_"))
        write(root, "gen/sub/c.yaml", body.replace("key_", "alt_"))
        a = analyze_project(root)
        # Every file under gen/ is generated-flagged, so gen/ earns
        # the exclude glob; the config-shaped gen/sub must NOT also
        # earn a structure glob that could outrank it (F2).
        assert a["modes"] == {"gen/**": "exclude"}

    def test_generated_file_with_metachar_name_dropped_loudly(self, tmp_path):
        root = tmp_path / "metachar"
        root.mkdir()
        write(root, "src/gen[1].py",
              "# @generated by fixture\n\n\ndef fetch():\n    return None\n")
        write(root, "src/real.py", "def real():\n    return 1\n")
        a = analyze_project(root)
        assert a["modes"] == {}
        assert any("does not match" in w or "dropped" in w
                   for w in a["mode_why"])

    def test_interactive_budget_locked_by_flag(self, py_app):
        # Prompts are printed into the `out` stream by _ask, so a
        # locked budget is proven by the absence of a Budget prompt.
        out = io.StringIO()
        code, payload = run_init(py_app, interactive=True, dry_run=True,
                                 budget=777777,
                                 input_fn=lambda: "", out=out)
        assert code == 0
        assert payload["profile"]["budget_tokens"] == 777777
        assert "Budget:" not in out.getvalue()


