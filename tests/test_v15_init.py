class TestEntryCandidates:
    def test_ranking_order_and_signals(self, py_app):
        cands = find_entry_candidates(scan(py_app))
        paths = [c["path"] for c in cands]
        assert paths[:2] == ["src/main.py", "src/cli.py"]
        main_signals = " ".join(cands[0]["signals"])
        assert "[project.scripts]" in main_signals
        assert "__main__" in main_signals
        cli_signals = " ".join(cands[1]["signals"])
        assert "shebang" in cli_signals

    def test_test_files_and_vendored_never_candidates(self, py_app):
        paths = [c["path"] for c in find_entry_candidates(scan(py_app))]
        assert "tests/test_app.py" not in paths      # __main__ guard, but a test
        assert "vendor/pkg/index.js" not in paths    # entry name, but vendored
        assert "src/lib.py" not in paths             # imported, no signal

    def test_npm_bin_and_main_signals(self, js_mono):
        cands = {c["path"]: c for c in find_entry_candidates(scan(js_mono))}
        assert "packages/web/cli.js" in cands
        assert any('"bin"' in s for s in cands["packages/web/cli.js"]["signals"])
        assert "packages/web/index.js" in cands
        assert any('"main"' in s for s in cands["packages/web/index.js"]["signals"])
        assert "packages/api/server.js" in cands     # name heuristic
        # cli.js: bin (60) + name heuristic (40) + shebang (25)
        #         + no-importers (10) = 135
        # index.js: main (50) + name heuristic (40) + no-importers (10) = 100
        assert cands["packages/web/cli.js"]["score"] == 135
        assert cands["packages/web/index.js"]["score"] == 100


