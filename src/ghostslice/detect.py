"""Generated / minified / vendored detection (v0.12).

One shared detection module. G6's lint rules (L006 giant-line, L007
stale-generated) first detected these shapes privately; G7 lifts the
detection into a single place and wires it into the scanner (per-file
flags on FileEntry), the exporter (--auto-shrink, opt-in), explain,
and the same lint rules, so every surface agrees on what counts as
generated, minified, or vendored.

Design rules, in order of importance:

1. CONSERVATIVE. A hit needs textual or path evidence. Hand-written
   code is never relabelled on vibes: long lines alone do not make a
   file minified (the minified verdict is the token estimator's own
   calibrated shape test, tokens.looks_minified — imported, never
   cloned, so the family calibration and this module cannot drift),
   a "generated" mention deep in a file does not make it generated
   (header window only), and a directory merely *named like* a vendor
   dir ("vendors/", "myvendor/") does not make its files vendored
   (exact path segment only).

2. EVIDENCE IS METADATA, NEVER CONTENT. Every detector returns
   (hit, evidence) where evidence is drawn from this module's own
   vocabulary — a canonical marker string from GENERATED_MARKERS, a
   path segment, line statistics — plus, for vendored banners, the
   banner's library name token (the banner is a public license
   header; it is the marker itself). File content beyond the marker
   never appears in evidence, so flags are safe to print, serialise,
   and ship in a bundle manifest.

3. HEAD-ONLY, WITH ONE EXCEPTION. The generated and vendored
   detectors see only the first HEAD_CHARS characters of a file
   (the scanner slices them from the text it already read for
   token estimation — no second read). The minified verdict is
   the exception (audit G07 F1): looks_minified's thresholds are
   whole-text statistics and a 4KB head provably flips the verdict
   on hand-written code that opens with a dense block, so the
   minified detector judges the FULL text whenever the caller has
   it — the scanner always does, at no extra I/O. Callers holding
   only a head get the weaker head-shaped verdict, documented as
   such at detect_minified.

Scope (which languages each detector applies to):
- generated: every language EXCEPT markdown (prose: a README saying
  "generated by the build, do not edit" is documentation, not a
  generated file) and notebook (the raw text is JSON wrapping; header
  markers inside it are unreliable). Plain .txt stays in scope —
  generated data dumps conventionally carry the same header markers,
  and lint L007 has flagged them since v0.11.
- minified: code/data languages only (the SLICABLE code languages
  plus json/yaml/toml/sql/shell/powershell config-data). Prose and
  plain text are out: a long-line text file is prose shape, not
  minified code.
- vendored: the PATH check applies to every file — a file's location
  under vendor/ is objective evidence whatever its type (vendored
  docs are still vendored content); the BANNER check is scoped like
  generated (code/data/text, not markdown/notebook).
"""
from __future__ import annotations

import math
import re
from pathlib import Path

from .tokens import looks_minified

HEAD_CHARS = 4096          # ~first 4KB of a file, as characters
GENERATED_HEADER_LINES = 15

# Canonical generated-code header markers, matched case-insensitively
# against the first GENERATED_HEADER_LINES lines. Order is the match
# order: more specific phrases first, so the evidence names the most
# precise marker present. This is the v0.11 L007 list plus thrift's
# "autogenerated by".
GENERATED_MARKERS = (
    "@generated",
    "autogenerated by",
    "code generated",
    "generated by",
    "do not edit",
    "auto-generated",
    "automatically generated",
)

# Exact directory segments that mark an in-tree vendored subtree.
VENDOR_DIRS = ("vendor", "third_party", "extern")

# Languages the content detectors (generated markers, vendored
# banners) skip: prose and JSON-wrapped notebooks.
_NO_CONTENT_DETECT = {"markdown", "notebook"}

# Languages the minified verdict applies to: code + structured data.
_MINIFIED_LANGUAGES = {
    "python", "typescript", "javascript", "go", "rust", "java",
    "csharp", "php", "ruby", "kotlin", "swift", "c", "cpp", "scala",
    "json", "yaml", "toml", "sql", "shell", "powershell",
}

# "/*! jQuery v3.7.1 | (c) OpenJS Foundation */" — the /*! ... */
# banner is how minified/vendored JS libraries keep their license
# header through the minifier. Capture is the library name plus an
# optional version: the marker itself, never surrounding code.
_BANNER_RE = re.compile(r"^\s*/\*!\s*([A-Za-z][\w.+-]*(?:\s+v?\d[\w.]*)?)")


def head_of(text: str) -> str:
    """The detector input: the first HEAD_CHARS characters."""
    return text[:HEAD_CHARS]


def line_stats(text: str) -> dict:
    """Line-shape statistics for a text: count, longest, mean, p95.

    The single stats implementation — lint L006 consumes this too
    (it previously computed the same numbers inline)."""
    lengths = sorted(len(ln) for ln in text.splitlines())
    if not lengths:
        return {"lines": 0, "longest": 0, "avg": 0.0, "p95": 0}
    return {
        "lines": len(lengths),
        "longest": lengths[-1],
        "avg": sum(lengths) / len(lengths),
        "p95": lengths[math.ceil(0.95 * len(lengths)) - 1],
    }


def detect_generated(path: str, language: str, head: str) -> tuple[bool, str]:
    """Header-marker check: a canonical marker in the first
    GENERATED_HEADER_LINES lines. Evidence is the canonical marker
    string from GENERATED_MARKERS, not the file's own line."""
    if language in _NO_CONTENT_DETECT:
        return False, ""
    header = "\n".join(head.splitlines()[:GENERATED_HEADER_LINES]).lower()
    for marker in GENERATED_MARKERS:
        if marker in header:
            return True, marker
    return False, ""


def detect_minified(path: str, language: str, head: str,
                    stats: dict | None = None,
                    text: str | None = None) -> tuple[bool, str]:
    """Minified verdict: tokens.looks_minified, the calibrated
    estimator's own shape test (very long lines AND a high mean line
    length over a minimum size), reused verbatim so the estimator's
    minified-js family and this flag are the same judgement. The
    evidence is line statistics, never content.

    The verdict judges `text` (the full file) when the caller has
    it — audit G07 F1: judged on a 4KB head alone, the whole-text
    thresholds misfire on hand-written files whose opening block is
    dense. With only `head` available the verdict is head-shaped
    and weaker; prefer passing the full text."""
    if language not in _MINIFIED_LANGUAGES:
        return False, ""
    judged = text if text is not None else head
    if not looks_minified(judged):
        return False, ""
    stats = stats if stats is not None else line_stats(judged)
    return True, (f"line shape: longest {stats['longest']:,} chars, "
                  f"avg {stats['avg']:.0f} chars/line")


def detect_vendored(path: str, language: str, head: str) -> tuple[bool, str]:
    """Vendored check: exact vendor-directory path segment (any
    language — location is the evidence), or a /*! ... */ library
    license banner in the head (scoped like generated)."""
    parts = [p.lower() for p in Path(path).parts[:-1]]
    for seg in VENDOR_DIRS:
        if seg in parts:
            return True, f"vendored path ({seg}/)"
    if language not in _NO_CONTENT_DETECT:
        for line in head.splitlines()[:GENERATED_HEADER_LINES]:
            m = _BANNER_RE.match(line)
            if m:
                return True, f"library banner /*! {m.group(1)}"
    return False, ""


def detect_all(path: str, language: str, head: str,
               text: str | None = None) -> dict[str, str]:
    """Run every detector over (path, language, head text).
    Returns {kind: evidence} for hits only, kind in
    {"generated", "minified", "vendored"}. Pass the full file as
    `text` when available: the minified verdict needs it (F1);
    the other detectors stay head-only regardless."""
    out: dict[str, str] = {}
    hit, ev = detect_generated(path, language, head)
    if hit:
        out["generated"] = ev
    hit, ev = detect_minified(path, language, head, text=text)
    if hit:
        out["minified"] = ev
    hit, ev = detect_vendored(path, language, head)
    if hit:
        out["vendored"] = ev
    return out
