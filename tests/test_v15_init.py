class TestAnalysis:
    def test_profile_sections_from_evidence(self, py_app):
        a = analyze_project(py_app)
        assert a["entry_points"][0] == "src/main.py"
        assert a["ignore"] == ["vendor/**"]
        assert a["modes"] == {"src/gen/**": "exclude"}
        assert a["model"] is None

    def test_config_dir_gets_structure(self, tmp_path):
        root = tmp_path / "cfgproj"
        root.mkdir()
        body = "".join(f"key_{i}: value-{i}\n" for i in range(45))
        write(root, "config/a.yaml", body)
        write(root, "config/b.yaml", body.replace("key_", "opt_"))
        write(root, "config/c.toml",
              "".join(f'key_{i} = "value-{i}"\n' for i in range(45)))
        a = analyze_project(root)
        assert a["modes"] == {"config/**": "structure"}

    def test_budget_rounding(self):
        assert round_budget(12500) == 13000
        assert round_budget(999) == 1000
        assert round_budget(5) == 5
        assert round_budget(0) == 0

    def test_tiny_project_omits_budget(self, tmp_path):
        root = tmp_path / "tiny"
        root.mkdir()
        write(root, "a.py", "x = 1\n")
        a = analyze_project(root)
        assert a["budget_tokens"] is None
        assert "omitted" in a["budget_why"]

    def test_big_project_budget_basis(self, tmp_path):
        root = tmp_path / "big"
        root.mkdir()
        write(root, "docs/big.md",
              "alpha beta gamma delta epsilon zeta eta theta iota kappa " * 3000)
        a = analyze_project(root)
        assert a["sliced_tokens"] >= 5000
        expected = round_budget(a["sliced_tokens"] * 1.25)
        assert a["budget_tokens"] == expected
        assert str(a["sliced_tokens"]) in a["budget_why"].replace(",", "")

    def test_budget_override_not_rounded(self, py_app):
        a = analyze_project(py_app, budget_override=424242)
        assert a["budget_tokens"] == 424242
        assert "--budget" in a["budget_why"]

    def test_model_only_from_flag(self, py_app):
        assert analyze_project(py_app, model_id="claude-sonnet")["model"] == "claude-sonnet"


