def _snapshot(root: Path) -> dict[str, bytes]:
    return {str(p.relative_to(root)): p.read_bytes()
            for p in sorted(root.rglob("*")) if p.is_file()}


class TestRunInit:
    def test_writes_profile_that_loads(self, py_app):
        out = io.StringIO()
        code, payload = run_init(py_app, yes=True, out=out)
        assert code == 0 and payload["written"]
        target = py_app / ".ghostslice.json"
        text = target.read_text(encoding="utf-8")
        assert text.endswith("\n")
        data = json.loads(text)
        assert list(data.keys()) == [k for k in
                                      ("ignore", "modes", "model", "budget_tokens",
                                       "entry_points", "preset", "lint")
                                      if k in data]
        loaded = load_profile(py_app)
        assert loaded.ignore == ["vendor/**"]
        assert loaded.modes == {"src/gen/**": "exclude"}
        assert loaded.entry_points[0] == "src/main.py"
        assert "Biggest wins" in out.getvalue()

    def test_round_trip_export_modes_take_effect(self, py_app):
        code, _ = run_init(py_app, yes=True, out=io.StringIO())
        assert code == 0
        profile = load_profile(py_app)
        bundle = py_app.parent / "bundle-init"
        manifest = build_bundle(py_app, bundle, profile=profile, record_history=False)
        by_path = {f["path"]: f for f in manifest["files"]}
        # ignored by the profile: not even scanned into the bundle.
        assert "vendor/pkg/index.js" not in by_path
        assert by_path["src/gen/client.py"]["mode"] == "exclude"
        assert validate_bundle(bundle)["ok"]
        plain = build_bundle(py_app, py_app.parent / "bundle-plain",
                             record_history=False)
        assert manifest["total_sliced_tokens"] < plain["total_sliced_tokens"]

    def test_dry_run_writes_nothing(self, py_app):
        before = _snapshot(py_app)
        code, payload = run_init(py_app, yes=True, dry_run=True, out=io.StringIO())
        assert code == 0 and not payload["written"]
        assert _snapshot(py_app) == before
        assert not (py_app / ".ghostslice.json").exists()

    def test_refuses_existing_without_force(self, py_app):
        target = write(py_app, ".ghostslice.json", '{"budget_tokens": 1234}\n')
        err = io.StringIO()
        code, _ = run_init(py_app, yes=True, out=io.StringIO(), err=err)
        assert code == 2
        assert target.read_text(encoding="utf-8") == '{"budget_tokens": 1234}\n'
        assert "already exists" in err.getvalue()
        assert "budget_tokens 1,234" in err.getvalue()

    def test_force_overwrites(self, py_app):
        write(py_app, ".ghostslice.json", '{"budget_tokens": 1234}\n')
        code, payload = run_init(py_app, yes=True, force=True, out=io.StringIO())
        assert code == 0 and payload["written"]
        assert load_profile(py_app).entry_points  # the tuned profile, not the stub

    def test_second_run_refuses(self, py_app):
        assert run_init(py_app, yes=True, out=io.StringIO())[0] == 0
        assert run_init(py_app, yes=True, out=io.StringIO(), err=io.StringIO())[0] == 2

    def test_missing_project_raises(self, tmp_path):
        with pytest.raises(FileNotFoundError):
            run_init(tmp_path / "nope", yes=True, out=io.StringIO())

    def test_profile_path_that_is_a_directory_refused(self, py_app):
        # Audit G10 G1: exists-but-not-a-file must be a clean exit 2,
        # never a traceback from write_text.
        (py_app / ".ghostslice.json").mkdir()
        err = io.StringIO()
        code, _ = run_init(py_app, yes=True, force=True,
                           out=io.StringIO(), err=err)
        assert code == 2
        assert (py_app / ".ghostslice.json").is_dir()
        assert "not a file" in err.getvalue()


