def write(root: Path, rel: str, text: str) -> None:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


def write_profile(root: Path, data: dict) -> None:
    write(root, ".ghostslice.json", json.dumps(data))


def run_cli(argv) -> tuple[int, str, str]:
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = cli_main(argv)
    return code, out.getvalue(), err.getvalue()


GEN_HEADER = "# Code generated by protoc-gen. DO NOT EDIT.\n"
MIN_LINE = "var data = '" + "abcd" * 220 + "';"
MINIFIED_JS = "\n".join([MIN_LINE, MIN_LINE, MIN_LINE]) + "\n"


def fat_python(nfuncs: int = 60, prefix: str = "") -> str:
    parts = [prefix] if prefix else []
    for i in range(nfuncs):
        parts.append(f"def handler_{i}(request):")
        for j in range(10):
            parts.append(f"    value_{j} = request.field_{j} + {j} * {i}")
        parts.append("    return value_0")
        parts.append("")
    return "\n".join(parts)


class DetectCase(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)

    def tearDown(self):
        self.tmp.cleanup()


class TestGeneratedDetector(DetectCase):
    def test_protoc_header_hits_with_canonical_marker(self):
        hit, ev = detect_generated("gen.py", "python", GEN_HEADER + "x = 1\n")
        self.assertTrue(hit)
        self.assertEqual(ev, "code generated")  # canonical, not file text

    def test_at_generated_and_thrift_variants(self):
        hit, ev = detect_generated("a.js", "javascript", "// @generated\ncode();\n")
        self.assertTrue(hit)
        self.assertEqual(ev, "@generated")
        hit, ev = detect_generated("a.java", "java",
                                   "/** Autogenerated by Thrift Compiler */\n")
        self.assertTrue(hit)
        self.assertEqual(ev, "autogenerated by")

    def test_marker_beyond_header_window_is_silent(self):
        body = "filler line\n" * 20 + "this was generated by hand\n"
        hit, _ = detect_generated("late.py", "python", body)
        self.assertFalse(hit)

    def test_readme_prose_is_out_of_scope(self):
        text = "# Notes\n\nThis file is generated by the build. Do not edit.\n"
        hit, _ = detect_generated("README.md", "markdown", text)
        self.assertFalse(hit)
        self.assertEqual(detect_all("README.md", "markdown", text), {})

    def test_notebook_is_out_of_scope(self):
        hit, _ = detect_generated("n.ipynb", "notebook", GEN_HEADER)
        self.assertFalse(hit)


class TestMinifiedDetector(DetectCase):
    def test_minified_js_hits(self):
        hit, ev = detect_minified("min.js", "javascript", MINIFIED_JS)
        self.assertTrue(hit)
        self.assertIn("line shape", ev)
        self.assertNotIn("abcd", ev)  # evidence is stats, never content

    def test_handwritten_long_line_file_is_silent(self):
        lines = ["// the template below is one long literal, the rest is prose-like code",
                 "const template = \"" + "x" * 500 + "\";"]
        lines += [f"const v{i} = {i};" for i in range(30)]
        text = "\n".join(lines) + "\n"
        hit, _ = detect_minified("app.js", "javascript", text)
        self.assertFalse(hit)

    def test_compact_json_hits_but_text_is_out_of_scope(self):
        blob = json.dumps({f"key_{i}": f"value_{i}" * 5 for i in range(40)})
        self.assertGreater(len(blob), 400)
        hit, _ = detect_minified("data.json", "json", blob)
        self.assertTrue(hit)
        hit, _ = detect_minified("data.txt", "text", blob)
        self.assertFalse(hit)

    def test_tiny_single_line_is_silent(self):
        hit, _ = detect_minified("s.js", "javascript", "x" * 300)
        self.assertFalse(hit)


class TestVendoredDetector(DetectCase):
    def test_vendor_path_segments_hit(self):
        for rel in ("vendor/jquery.js", "third_party/foo/bar.py", "extern/lib.c"):
            hit, ev = detect_vendored(rel, "javascript", "plain code\n")
            self.assertTrue(hit, rel)
            self.assertIn("vendored path", ev)

    def test_lookalike_directories_are_silent(self):
        for rel in ("src/vendors/x.js", "myvendor/x.js", "vendorish/x.js"):
            hit, _ = detect_vendored(rel, "javascript", "plain code\n")
            self.assertFalse(hit, rel)

    def test_library_banner_hits(self):
        text = "/*! jQuery v3.7.1 | (c) OpenJS Foundation */\ncode();\n"
        hit, ev = detect_vendored("jquery.js", "javascript", text)
        self.assertTrue(hit)
        self.assertIn("jQuery v3.7.1", ev)

    def test_plain_comment_is_not_a_banner(self):
        hit, _ = detect_vendored("a.js", "javascript", "/* just a comment */\nx();\n")
        self.assertFalse(hit)


class TestMinifiedHeadVsFull(DetectCase):
    """Audit F1 regression: a hand-written file whose opening block
    is dense (long one-line records) but whose whole-file shape is
    normal code must NOT be flagged minified. looks_minified's
    thresholds are whole-text statistics; judged on the head alone
    this exact shape flips to a hit — that weaker head-only form is
    what detect_minified falls back to when no full text is given,
    and the scanner never relies on it."""

    DENSE_HEAD = "\n".join(
        ["export const TOOLS = ["]
        + [f"  {{ name: 'tool_{i}', description: '" + "long description " * 20
           + f"', schema: {{}} }}," for i in range(18)]
        + ["];"]
        + [f"export function helper_{i}(x) {{" for i in range(40)]
        + ["  return x + 1;", "}"] * 1
        + [f"const v{i} = {i};" for i in range(40)]) + "\n"

    def test_dense_head_file_not_minified_via_scanner(self):
        write(self.root, "tools.js", self.DENSE_HEAD)
        result = scan(self.root)
        entry = {f.path: f for f in result.files}["tools.js"]
        self.assertFalse(entry.is_minified)
        self.assertNotIn("minified", entry.detect_evidence)

    def test_full_text_verdict_and_head_fallback_differ(self):
        # The documented F1 mechanism, pinned: full text -> no hit;
        # head-only fallback -> hit (weaker form, unused by scanner).
        hit, _ = detect_minified("tools.js", "javascript",
                                 head_of(self.DENSE_HEAD),
                                 text=self.DENSE_HEAD)
        self.assertFalse(hit)
        hit, _ = detect_minified("tools.js", "javascript",
                                 head_of(self.DENSE_HEAD))
        self.assertTrue(hit)


class TestLineStats(DetectCase):
    def test_stats_shape(self):
        stats = line_stats("ab\nabcd\nx\n")
        self.assertEqual(stats["lines"], 3)
        self.assertEqual(stats["longest"], 4)
        self.assertAlmostEqual(stats["avg"], 7 / 3)
        self.assertEqual(stats["p95"], 4)
        self.assertEqual(line_stats(""), {"lines": 0, "longest": 0, "avg": 0.0, "p95": 0})


class TestScannerFlags(DetectCase):
    def test_flags_and_evidence_on_entries(self):
        write(self.root, "gen.py", GEN_HEADER + "def f():\n    return 1\n")
        write(self.root, "min.js", MINIFIED_JS)
        write(self.root, "vendor/lib.js", "function lib() {\n  return 1;\n}\n")
        write(self.root, "app.py", "def main():\n    return 1\n")
        result = scan(self.root)
        by = {f.path: f for f in result.files}
        self.assertTrue(by["gen.py"].is_generated)
        self.assertEqual(by["gen.py"].detect_evidence["generated"], "code generated")
        self.assertTrue(by["min.js"].is_minified)
        self.assertTrue(by["vendor/lib.js"].is_vendored)
        self.assertFalse(by["app.py"].is_generated)
        self.assertEqual(by["app.py"].detect_evidence, {})
        d = by["gen.py"].to_dict()
        self.assertTrue(d["is_generated"])
        self.assertIn("detect_evidence", d)

    def test_scan_cli_text_and_json_surface_flags(self):
        write(self.root, "gen.py", GEN_HEADER + "def f():\n    return 1\n")
        code, out, _ = run_cli(["scan", str(self.root)])
        self.assertEqual(code, 0)
        self.assertIn("[generated]", out)
        code, out, _ = run_cli(["scan", str(self.root), "--json"])
        data = json.loads(out)
        entry = {f["path"]: f for f in data["files"]}["gen.py"]
        self.assertTrue(entry["is_generated"])
        self.assertEqual(entry["detect_evidence"]["generated"], "code generated")


class TestLintConsumption(DetectCase):
    def test_l007_fires_via_detect_with_canonical_marker(self):
        write(self.root, "gen.txt", "// Code generated by protoc-gen. DO NOT EDIT.\n"
              + "payload line\n" * 30)
        payload = lint_project(self.root, profile=load_profile(self.root))
        hits = [f for f in payload["findings"] if f["rule"] == "L007"]
        self.assertEqual(len(hits), 1)
        self.assertIn("'code generated'", hits[0]["message"])
        self.assertIn("first 15 lines", hits[0]["message"])

    def test_l007_markdown_prose_now_silent(self):
        # Behaviour change vs v0.11, deliberate: prose is out of
        # detect.py's scope, so a README at full mode no longer
        # draws a stale-generated warning.
        write(self.root, "README.md",
              "# Docs\n\nThis page was generated by hand. Do not edit.\n" + "word " * 50)
        payload = lint_project(self.root, profile=load_profile(self.root))
        self.assertEqual([f for f in payload["findings"] if f["rule"] == "L007"], [])

    def test_l006_fires_where_minified_verdict_does_not(self):
        # L006 is the giant-line rule (any language, stats via
        # detect.line_stats); the minified VERDICT is narrower.
        write(self.root, "prose.txt", ("word " * 90 + "\n") * 20)
        result = scan(self.root)
        entry = {f.path: f for f in result.files}["prose.txt"]
        self.assertFalse(entry.is_minified)  # text is out of scope
        payload = lint_project(self.root, profile=load_profile(self.root))
        hits = [f for f in payload["findings"]
                if f["rule"] == "L006" and f["path"] == "prose.txt"]
        self.assertEqual(len(hits), 1)

    def test_minified_fixture_still_fires_l006(self):
        write(self.root, "min.js", MINIFIED_JS)
        payload = lint_project(self.root, profile=load_profile(self.root))
        hits = [f for f in payload["findings"] if f["rule"] == "L006"]
        self.assertEqual(len(hits), 1)


def shrink_project(root: Path) -> None:
    write(root, "app.py", "def main():\n    return helper()\n\n\ndef helper():\n    return 1\n")
    write(root, "gen.py", GEN_HEADER + fat_python(10))
    write(root, "vendor/lib.js", "function lib() {\n  return 1;\n}\n" + "var x = 1;\n" * 20)
    write(root, "min.js", MINIFIED_JS)


def manifest_modes(manifest) -> dict:
    return {f["path"]: f for f in manifest["files"]}


class TestAutoShrink(DetectCase):
    def test_off_by_default_changes_nothing(self):
        shrink_project(self.root)
        result = scan(self.root)
        plain = resolve_modes(result)
        manifest = build_bundle(self.root, self.root / "bundle",
                                record_history=False)
        modes = manifest_modes(manifest)
        self.assertEqual({p: f["mode"] for p, f in modes.items()}, plain)
        self.assertTrue(all("mode_reason" not in f for f in modes.values()))
        self.assertEqual(modes["gen.py"]["mode"], "signatures")
        self.assertEqual(modes["min.js"]["mode"], "signatures")

    def test_flag_excludes_detected_with_reasons(self):
        shrink_project(self.root)
        manifest = build_bundle(self.root, self.root / "bundle",
                                auto_shrink=True, record_history=False)
        modes = manifest_modes(manifest)
        self.assertEqual(modes["gen.py"]["mode"], "exclude")
        self.assertEqual(modes["gen.py"]["mode_reason"],
                         "auto: generated (code generated)")
        self.assertEqual(modes["vendor/lib.js"]["mode"], "exclude")
        self.assertTrue(modes["vendor/lib.js"]["mode_reason"].startswith(
            "auto: vendored (vendored path (vendor/))"))
        self.assertEqual(modes["min.js"]["mode"], "exclude")
        self.assertTrue(modes["min.js"]["mode_reason"].startswith("auto: minified ("))
        self.assertEqual(modes["app.py"]["mode"], "signatures")
        self.assertNotIn("mode_reason", modes["app.py"])
        self.assertEqual(manifest["total_sliced_tokens"],
                         modes["app.py"]["sliced_tokens"])

    def test_profile_option_enables_without_flag(self):
        shrink_project(self.root)
        write_profile(self.root, {"auto_shrink": True})
        manifest = build_bundle(self.root, self.root / "bundle",
                                profile=load_profile(self.root),
                                record_history=False)
        self.assertEqual(manifest_modes(manifest)["gen.py"]["mode"], "exclude")

    def test_profile_option_validates_type(self):
        write_profile(self.root, {"auto_shrink": "yes"})
        with self.assertRaises(ValueError):
            load_profile(self.root)

    def test_explicit_profile_mode_beats_auto(self):
        shrink_project(self.root)
        write_profile(self.root, {"modes": {"gen.py": "full"}})
        manifest = build_bundle(self.root, self.root / "bundle",
                                profile=load_profile(self.root),
                                auto_shrink=True, record_history=False)
        modes = manifest_modes(manifest)
        self.assertEqual(modes["gen.py"]["mode"], "full")
        self.assertNotIn("mode_reason", modes["gen.py"])

    def test_explicit_selection_beats_auto(self):
        shrink_project(self.root)
        manifest = build_bundle(self.root, self.root / "bundle",
                                selections={"gen.py": "signatures"},
                                auto_shrink=True, record_history=False)
        modes = manifest_modes(manifest)
        self.assertEqual(modes["gen.py"]["mode"], "signatures")
        self.assertNotIn("mode_reason", modes["gen.py"])

    def test_caller_default_mode_beats_auto(self):
        shrink_project(self.root)
        manifest = build_bundle(self.root, self.root / "bundle",
                                default_mode="full",
                                auto_shrink=True, record_history=False)
        modes = manifest_modes(manifest)
        self.assertEqual(modes["gen.py"]["mode"], "full")
        self.assertNotIn("mode_reason", modes["gen.py"])

    def test_entry_point_is_never_auto_excluded(self):
        # Audit F2: naming a file as a profile entry point is an
        # explicit signal; auto-shrink must not override it even
        # when the file carries a generated header.
        shrink_project(self.root)
        write_profile(self.root, {"auto_shrink": True,
                                  "entry_points": ["gen.py"]})
        manifest = build_bundle(self.root, self.root / "bundle",
                                profile=load_profile(self.root),
                                record_history=False)
        modes = manifest_modes(manifest)
        self.assertEqual(modes["gen.py"]["mode"], "signatures")
        self.assertNotIn("mode_reason", modes["gen.py"])
        # ...while the non-entry detected files still shrink.
        self.assertEqual(modes["min.js"]["mode"], "exclude")

    def test_lint_modes_track_auto_shrink_profile(self):
        # resolve_modes is shared: with the profile option on, lint
        # judges the same (shrunk) selection the exporter produces.
        shrink_project(self.root)
        write_profile(self.root, {"auto_shrink": True})
        payload = lint_project(self.root, profile=load_profile(self.root))
        self.assertEqual(payload["modes"]["gen.py"], "exclude")
        self.assertEqual(payload["modes"]["app.py"], "signatures")

    def test_cli_flag_and_output(self):
        shrink_project(self.root)
        code, out, _ = run_cli(["export", str(self.root), "-o",
                                str(self.root / "bundle"), "--auto-shrink"])
        self.assertEqual(code, 0)
        self.assertIn("Auto-shrink: excluded 3 detected file(s)", out)
        self.assertIn("auto: generated (code generated)", out)


class TestFitAfterAutoShrink(DetectCase):
    def test_auto_shrink_applies_before_fit_ladder(self):
        write(self.root, "gen.py", GEN_HEADER + fat_python(60))
        write(self.root, "app.py", fat_python(60, prefix=""))
        # Budget sized so app.py alone at signatures fits, gen.py
        # must not be part of fit's work at all.
        plain = build_bundle(self.root, self.root / "b0", record_history=False)
        app_only = next(f for f in plain["files"] if f["path"] == "app.py")
        budget = app_only["sliced_tokens"] + 50
        manifest = build_bundle(self.root, self.root / "b1",
                                auto_shrink=True, fit=budget,
                                record_history=False)
        modes = manifest_modes(manifest)
        self.assertEqual(modes["gen.py"]["mode"], "exclude")
        self.assertEqual(modes["gen.py"]["mode_reason"],
                         "auto: generated (code generated)")
        self.assertTrue(manifest["fit"]["fitted"])
        self.assertLessEqual(manifest["total_sliced_tokens"], budget)
        downgraded = {d["path"] for d in manifest["fit"]["downgraded"]}
        self.assertNotIn("gen.py", downgraded)


class TestExplainAndDashboard(DetectCase):
    def test_explain_shows_detection(self):
        write(self.root, "gen.py", GEN_HEADER + "def f():\n    return 1\n")
        write(self.root, "app.py", "def main():\n    return 1\n")
        code, out, _ = run_cli(["explain", str(self.root), "gen.py"])
        self.assertEqual(code, 0)
        self.assertIn("detection: generated (code generated)", out)
        code, out, _ = run_cli(["explain", str(self.root), "app.py"])
        self.assertEqual(code, 0)
        self.assertIn("detection: none", out)

    def test_watch_export_passes_auto_shrink(self):
        from ghostslice.watch import run_watch
        shrink_project(self.root)
        bundle = self.root / "bundle-out"
        run_watch(self.root, out=bundle, export=True, once=True,
                  auto_shrink=True, profile=load_profile(self.root))
        manifest = json.loads((bundle / "manifest.json").read_text())
        modes = manifest_modes(manifest)
        self.assertEqual(modes["gen.py"]["mode"], "exclude")
        self.assertEqual(modes["gen.py"]["mode_reason"],
                         "auto: generated (code generated)")

    def test_dashboard_api_scan_carries_flags(self):
        write(self.root, "gen.py", GEN_HEADER + "def f():\n    return 1\n")
        server, _ = make_server(str(self.root), port=0)
        port = server.server_address[1]
        thread = threading.Thread(target=lambda: server.serve_forever(poll_interval=0.02), daemon=True)
        thread.start()
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}/api/scan",
                                        timeout=10) as r:
                self.assertEqual(r.status, 200)
                data = json.loads(r.read().decode("utf-8"))
        finally:
            server.shutdown()
            server.server_close()
        entry = {f["path"]: f for f in data["files"]}["gen.py"]
        self.assertTrue(entry["is_generated"])
        self.assertEqual(entry["detect_evidence"]["generated"], "code generated")


